// src/extensions/codemirror/symbolPalette/symbolPaletteData.ts
// The symbol palette's symbols, as on Overleaf: the LaTeX command, its
// Unicode character (shown in search and inserted in Typst when Typst has
// no name for it), Typst's name, and the package the command needs. Each
// command was compiled with pdflatex, with its package and without (where
// it then fails), and drawn with KaTeX. The English description is the
// translation key, read when shown so that a change of language applies.
import { t } from '@/i18n';

export type SymbolCategory =
	| 'greek'
	| 'arrows'
	| 'operators'
	| 'relations'
	| 'misc';

export interface PaletteSymbol {
	category: SymbolCategory;
	command: string;
	char: string;
	/** Typst's name; Typst takes the character itself otherwise. */
	typst?: string;
	/** The description in English, searched in any language. */
	en: string;
	description: () => string;
	package?: string;
	/** Valid outside math too. */
	text?: boolean;
	/** More English words to search by. */
	aliases?: string;
}

const s = (
	category: SymbolCategory,
	command: string,
	char: string,
	typst: string | undefined,
	en: string,
	description: () => string,
	more: Pick<PaletteSymbol, 'package' | 'text' | 'aliases'> = {},
): PaletteSymbol => ({
	category,
	command,
	char,
	...(typst ? { typst } : {}),
	en,
	description,
	...more,
});

